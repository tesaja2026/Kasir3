/*
# Add per-customer login codes

1. Modified Tables
- `customers`: adds `login_code` (text, unique). Each customer gets their own 6-character code generated by the store app. Customers use this personal code to log in to the catalog; orders they place are attributed to them via this identity.
- Backfills any existing rows with a random 6-char code so no customer is left without one.

2. Security
- No policy changes: customers table already has RLS with anon CRUD and grants.
*/

ALTER TABLE customers ADD COLUMN IF NOT EXISTS login_code text;

CREATE UNIQUE INDEX IF NOT EXISTS idx_customers_login_code ON customers(login_code);

UPDATE customers
SET login_code = upper(substring(replace(gen_random_uuid()::text, '-', ''), 1, 6))
WHERE login_code IS NULL;
